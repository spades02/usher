// The public API report (ADR 0010): every export of every entry point,
// printed from the built .d.ts files without comments, into api/*.api.md.
//
//   node scripts/api-report.mjs          # write the reports
//   node scripts/api-report.mjs --check  # fail if they differ (CI)
//
// A diff in a pull request is the reviewer's signal that the public surface
// changed, and that the changeset needs the right semver bump.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const check = process.argv.includes("--check");
const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

const entries = Object.entries(pkg.exports).map(([subpath, target]) => ({
  name: subpath === "." ? pkg.name : `${pkg.name}/${subpath.slice(2)}`,
  file: join(root, target.types),
}));
const program = ts.createProgram(
  entries.map((e) => e.file),
  { strict: true, skipLibCheck: true },
);
const checker = program.getTypeChecker();

function render(entry) {
  const source = program.getSourceFile(entry.file);
  if (!source) throw new Error(`Missing ${entry.file}: run the build first`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  const lines = [];
  for (const exported of checker.getExportsOfModule(moduleSymbol).sort((a, b) => a.name.localeCompare(b.name))) {
    const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    for (const decl of symbol.declarations ?? []) {
      const node = ts.isVariableDeclaration(decl) ? decl.parent.parent : decl;
      let text = printer.printNode(ts.EmitHint.Unspecified, node, decl.getSourceFile());
      if (symbol.name !== exported.name) text = `// exported as ${exported.name}\n${text}`;
      lines.push(text.replace(/^export (declare )?/gm, ""));
    }
  }
  return `# API report: \`${entry.name}\`\n\nGenerated by \`scripts/api-report.mjs\`. Do not edit by hand.\n\n\`\`\`ts\n${lines.join("\n\n")}\n\`\`\`\n`;
}

const dir = join(root, "api");
await mkdir(dir, { recursive: true });
const stale = [];
for (const entry of entries) {
  const file = join(dir, `${entry.name.replace(/^@/, "").replaceAll("/", "__")}.api.md`);
  const next = render(entry);
  const current = await readFile(file, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") === next) continue;
  if (check) stale.push(file.slice(root.length));
  else await writeFile(file, next);
}
if (stale.length) {
  console.error(
    `The public API changed: ${stale.join(", ")}.\nRun \`pnpm --filter @usherjs/core api\`, commit the reports, and add a changeset with the right bump.`,
  );
  process.exit(1);
}
console.log(check ? "API reports are up to date." : `Wrote ${entries.length} API reports.`);
