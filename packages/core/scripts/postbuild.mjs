// Runs after `tsc`: replaces dist/ui/elements-script.js with a minified copy
// of the elements, served at {basePath}/elements.js (ADR 0009, ADR 0010).

import { writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { transform } from "esbuild";

const dist = fileURLToPath(new URL("../dist/", import.meta.url));
const { installUsherElements } = await import(pathToFileURL(`${dist}ui/elements.js`).href);

const { code } = await transform(`(${installUsherElements.toString()})(window);`, {
  minify: true,
  target: "es2022",
  legalComments: "none",
});
const script = `/* Usher elements (ADR 0009) */\n${code}`;

await writeFile(
  `${dist}ui/elements-script.js`,
  `// Generated by scripts/postbuild.mjs: the minified elements script.\nexport const ELEMENTS_SCRIPT = ${JSON.stringify(script)};\n`,
);
console.log(`elements.js: ${installUsherElements.toString().length} → ${script.length} bytes`);
